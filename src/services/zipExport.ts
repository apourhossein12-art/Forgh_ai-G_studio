import JSZip from 'jszip';
import { Project } from '../types';

export interface ExportZipResult {
  filename: string;
  filesCount: number;
  totalBytes: number;
  blobSize: number;
}

/**
 * Sanitizes a file path for safe inclusion in a zip archive.
 * Normalizes backslashes, strips leading/trailing slashes and parent traversal ("..").
 */
export function sanitizeZipPath(rawPath: string): string {
  let cleaned = rawPath.replace(/\\/g, '/').trim();
  // Strip leading slashes and dot-slashes
  cleaned = cleaned.replace(/^(\.\/|\/)+/, '');
  // Eliminate directory traversal sequences
  const parts = cleaned.split('/').filter((p) => p && p !== '.' && p !== '..');
  return parts.join('/');
}

/**
 * Creates a structured project manifest for NONONICK Forge archives.
 */
export function generateProjectManifest(project: Project, cleanFiles: { path: string; size: number; language: string }[]) {
  return {
    $schema: 'https://nononick-forge.internal/schemas/project-v1.json',
    generator: 'NONONICK Forge',
    forgeVersion: '1.0.0',
    name: project.name,
    description: project.description || '',
    language: project.language,
    entryPoint: project.activeFilePath,
    createdAt: project.createdAt,
    updatedAt: project.updatedAt,
    exportedAt: new Date().toISOString(),
    timeoutMs: project.timeoutMs || 10000,
    env: project.env || {},
    fileCount: cleanFiles.length,
    files: cleanFiles,
  };
}

/**
 * Generates an informative README.md if the project does not already contain one.
 */
export function generateProjectReadme(project: Project): string {
  const isPython = project.language === 'python';
  const runCmd = isPython
    ? `python3 ${project.activeFilePath || 'main.py'}`
    : `node ${project.activeFilePath || 'index.js'}`;

  const envLines = Object.entries(project.env || {}).length > 0
    ? Object.entries(project.env)
        .map(([k, v]) => `- \`${k}\`: \`${v}\``)
        .join('\n')
    : '_None configured_';

  return `# ${project.name}

${project.description || 'Exported from NONONICK Forge cloud development environment.'}

---

## Runtime Details
- **Primary Language**: ${project.language.toUpperCase()}
- **Entry Point**: \`${project.activeFilePath || (isPython ? 'main.py' : 'index.js')}\`
- **Default Execution Timeout**: ${(project.timeoutMs || 10000) / 1000}s
- **Exported At**: ${new Date().toUTCString()}

## Local Execution
Run this project in your local terminal:

\`\`\`bash
${runCmd}
\`\`\`

## Configured Environment Variables
${envLines}

---
_Generated by NONONICK Forge — Production-Oriented Cloud Development Environment._
`;
}

/**
 * Bundles project files into a clean zip archive with a manifest,
 * and triggers a browser download.
 */
export async function exportProjectToZip(project: Project): Promise<ExportZipResult> {
  if (!project.files || project.files.length === 0) {
    throw new Error('Project contains no files to export.');
  }

  const zip = new JSZip();
  const cleanFilesSummary: { path: string; size: number; language: string }[] = [];
  let totalRawBytes = 0;
  let hasUserReadme = false;

  for (const file of project.files) {
    const cleanPath = sanitizeZipPath(file.path);
    if (!cleanPath) continue;

    if (cleanPath.toLowerCase() === 'readme.md') {
      hasUserReadme = true;
    }

    const content = file.content ?? '';
    totalRawBytes += content.length;

    zip.file(cleanPath, content, {
      date: new Date(project.updatedAt || Date.now()),
    });

    cleanFilesSummary.push({
      path: cleanPath,
      size: content.length,
      language: file.language || 'text',
    });
  }

  // 1. Add standardized Project Manifest
  const manifest = generateProjectManifest(project, cleanFilesSummary);
  zip.file('forge-project.json', JSON.stringify(manifest, null, 2), {
    date: new Date(),
  });

  // 2. Add companion manifest.json for generic tooling compatibility
  zip.file('manifest.json', JSON.stringify(manifest, null, 2), {
    date: new Date(),
  });

  // 3. Add default README.md if the project did not include one
  if (!hasUserReadme) {
    const defaultReadme = generateProjectReadme(project);
    zip.file('README.md', defaultReadme, {
      date: new Date(),
    });
    cleanFilesSummary.push({
      path: 'README.md',
      size: defaultReadme.length,
      language: 'markdown',
    });
  }

  // Generate ZIP blob with Deflate compression
  const zipBlob = await zip.generateAsync({
    type: 'blob',
    mimeType: 'application/zip',
    compression: 'DEFLATE',
    compressionOptions: {
      level: 6,
    },
  });

  // Format clean filename: e.g. "python_3_algorithmic_core.zip"
  const safeSlug = project.name
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9_-]+/g, '_')
    .replace(/^_+|_+$/g, '') || 'project';
  const filename = `${safeSlug}.zip`;

  // Trigger browser download
  const downloadUrl = URL.createObjectURL(zipBlob);
  const anchor = document.createElement('a');
  anchor.href = downloadUrl;
  anchor.download = filename;
  anchor.style.display = 'none';
  document.body.appendChild(anchor);
  anchor.click();

  // Cleanup
  setTimeout(() => {
    document.body.removeChild(anchor);
    URL.revokeObjectURL(downloadUrl);
  }, 1000);

  return {
    filename,
    filesCount: cleanFilesSummary.length,
    totalBytes: totalRawBytes,
    blobSize: zipBlob.size,
  };
}
